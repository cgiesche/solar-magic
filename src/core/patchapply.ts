// hook sites of the editor's own patches (SNES address, length)
interface Builtin { name: string; installed: (rom: Rom) => boolean; hooks: [number, number][] }
export const BUILTINS: Builtin[] = [
  { name: 'Editor patch (SMWE)', installed: (r) => !!editorPatch(r), hooks: EDITOR_HOOKS },
  { name: 'Level palettes (SMWP)', installed: (r) => !!customPalettePatch(r), hooks: PAL_HOOKS },
  { name: 'BG tilemaps (SMWB)', installed: (r) => !!bgPatch(r), hooks: BG_HOOKS },
  { name: 'Music per level (SMWU)', installed: (r) => !!musicPatch(r), hooks: MUSIC_HOOKS },
  { name: 'BG2/BG3 graphics (SMWG)', installed: (r) => !!extGfxPatch(r), hooks: EXT_GFX_HOOKS },
  { name: 'Messages (SMWM)', installed: (r) => !!messagePatch(r), hooks: MSG_HOOKS },
  { name: 'Structures (SMWS)', installed: (r) => !!structPatch(r), hooks: STRUCT_HOOKS },
  { name: 'Extended Map16 (SMWX)', installed: (r) => !!map16Ext(r), hooks: MAP16X_HOOKS },
  { name: 'Extended BG Map16 (SMWH)', installed: (r) => !!bgMap16Ext(r), hooks: BGMAP16_HOOKS },
];

// "smwe.asm", available to every patch (incsrc "smwe.asm"): the editor's RAM/ROM interfaces as defines
export function editorInclude(rom: Rom): string {
  const h = (n: number) => '$' + n.toString(16).toUpperCase().padStart(6, '0');
  const e = editorPatch(rom), p = customPalettePatch(rom), b = bgPatch(rom), x = map16Ext(rom), g = extGfxPatch(rom), bx = bgMap16Ext(rom);
  const lines = [
    '; generated by Solar Magic for the current ROM – see docs/patches.md',
    'if not(defined("SMWE_INCLUDED"))',
    '!SMWE_INCLUDED = 1',
    '!SMWE_LEVEL = $7E010B ; current level number (16 bit), set during level load',
    `!SMWE_PATCH = ${e ? 1 : 0}`,
    `!SMWE_SPRITE_BANKS = ${h(e?.sprBank ?? 0)} ; 512 bytes: bank of each level's sprite data`,
    `!SMWE_GFX_LO = ${h(e?.gfxLo ?? 0)}`, `!SMWE_GFX_HI = ${h(e?.gfxHi ?? 0)}`, `!SMWE_GFX_BANK = ${h(e?.gfxBank ?? 0)}`,
    `!SMWE_GFX_FLAGS = ${h(e?.gfxFlags ?? 0)} ; 256 bytes: 1 = raw 4bpp`,
    `!SMWE_LEVEL_GFX = ${h(e?.levelGfx ?? 0)} ; 512 x 8 bytes: GFX bypass (SP4..SP1, FG3, BG1, FG2, FG1), $FF = default`,
    `!SMWE_PALETTES = ${h(p?.table ?? 0)} ; 512 x 3 bytes: pointer to a level's 256-color palette, 0 = none`,
    `!SMWE_BG_BANKS = ${h(b?.table ?? 0)} ; 512 bytes: bank of a level's BG tilemap, 0 = vanilla`,
    `!SMWE_LEVEL_MUSIC = ${h(musicPatch(rom)?.table ?? 0)} ; 512 bytes: song of a level instead of its header setting, 0 = header`,
    `!SMWE_EXT_GFX = ${h(g?.table ?? 0)} ; 512 x 2 bytes: BG2/BG3 GFX file of a level (tiles 200-27F/280-2FF), $FF = none`,
    `!SMWE_MAP16X = ${x ? 1 : 0}`,
    `!SMWE_ACTS_LIKE = ${h(x?.acts ?? 0)} ; $1000 x 2 bytes: acts like of Map16 tiles 000-FFF`,
    `!SMWE_MAP16_GFX = ${h(x?.gfx ?? 0)} ; 8 bytes (4 tile words) per tile 200-FFF`,
    `!SMWE_BLOCKS = ${h(x?.blocks ?? 0)} ; $1000 x 4 bytes: custom block per tile (JMP table address, flags)`,
    `!SMWE_BG_MAP16_GFX = ${h(bx?.gfx ?? 0)} ; 8 bytes (4 tile words) per BG tile 200-FFF, 0 = no extended BG Map16`,
    'macro smwe_require(what)',
    '  if !SMWE_<what> == 0',
    '    error "This patch needs the editor feature <what> – enable it in Solar Magic first"',
    '  endif',
    'endmacro',
    'endif',
  ];
  return lines.join('\n') + '\n';
}

// header bytes that change with any expansion / checksum and are not part of a patch
const IGNORE: [number, number][] = [[0x7fd7, 1], [0x7fdc, 4]];

export interface PatchSource {
  name: string;
  version?: string;
  main: string;
  files: Map<string, Uint8Array | string>;
  defines?: Record<string, string>; // passed to Asar
  settings?: Record<string, string>; // all settings chosen by the user (stored in the registry)
  kind?: PatchEntry['kind'];
  archive?: Uint8Array; // sources to keep in the ROM (zip)
  ram?: RamClaim[]; // free RAM the patch uses
  // further Asar runs on the result of the previous ones, all recorded as this one patch (PIXI assembles
  // each sprite on its own); called with the results so far, null when done
  next?: (done: AsarResult[]) => { main: string; files?: Map<string, Uint8Array | string> } | null;
}

export interface ApplyResult {
  ok: boolean;
  errors: string[]; // German, ready to show
  warnings: string[];
  prints: string[];
  entry?: PatchEntry;
  labels?: Record<string, number>;
  steps?: AsarResult[]; // each Asar run (one unless the source has `next`)
  asar?: { errors: AsarMessage[]; warnings: AsarMessage[] };
}

const hex = (n: number, w = 6) => '$' + n.toString(16).toUpperCase().padStart(w, '0');
const pcHex = (pc: number) => hex(pcToSnes(pc));

export function sourceHash(src: PatchSource): string {
  const enc = new TextEncoder();
  const parts: Uint8Array[] = [];
  for (const k of [...src.files.keys()].sort()) {
    const v = src.files.get(k)!;
    parts.push(enc.encode(k), typeof v === 'string' ? enc.encode(v) : v);
  }
  parts.push(enc.encode(JSON.stringify(Object.entries(src.defines ?? {}).sort())));
  return hashBytes(parts).toString(16).padStart(8, '0');
}

// splits [pc, size) into the parts not covered by any of `cover`
function subtract(seg: [number, number], cover: [number, number][]): [number, number][] {
  let parts: [number, number][] = [seg];
  for (const [cs, cn] of cover) {
    const next: [number, number][] = [];
    for (const [s, n] of parts) {
      const e = s + n, ce = cs + cn;
      if (ce <= s || cs >= e) { next.push([s, n]); continue; }
      if (cs > s) next.push([s, cs - s]);
      if (ce < e) next.push([ce, e - ce]);
    }
    parts = next;
  }
  return parts;
}

// WRAM address ($7E0000-$7FFFFF) of a long address: banks $7E/$7F and the low RAM mirror; -1 if none
export function wramAddr(a: number): number {
  const bank = a >> 16, low = a & 0xffff;
  if (bank === 0x7e || bank === 0x7f) return a;
  if ((bank < 0x40 || (bank >= 0x80 && bank < 0xc0)) && low < 0x2000) return 0x7e0000 | low;
  return -1;
}

// RAM written with long addressing (STA long, STA long,X) by the bytes in `ranges`, merged into
// [snes, size]. A plain byte search: it finds the stores wherever they are in the code (also behind jump
// tables); a data byte that looks like one only matters if it hits another patch's RAM, and then gives a
// warning.
export function longWrites(data: Uint8Array, ranges: [number, number][]): [number, number][] {
  const found = new Set<number>();
  for (const [pc, n] of ranges) {
    for (let i = pc, e = Math.min(pc + n, data.length) - 3; i < e; i++) {
      if (data[i] !== 0x8f && data[i] !== 0x9f) continue;
      const w = wramAddr(data[i + 1] | (data[i + 2] << 8) | (data[i + 3] << 16));
      if (w >= 0) found.add(w);
    }
  }
  const out: [number, number][] = [];
  for (const a of [...found].sort((x, y) => x - y)) {
    const l = out[out.length - 1];
    if (l && l[0] + l[1] === a) l[1]++;
    else out.push([a, 1]);
  }
  return out;
}

const ramRange = (a: number, n: number) => n > 1 ? `${hex(a)}-${hex(a + n - 1)}` : hex(a);

// conflicts of a patch's RAM (claims, long writes) with the registered patches
export function ramConflicts(ram: RamClaim[], seen: [number, number][], others: PatchEntry[]): { errors: string[]; warnings: string[] } {
  const errors: string[] = [], warnings: string[] = [];
  for (const o of others) {
    for (const c of ram) {
      const d = o.ram?.find((x) => overlaps([x[0], x[1]], [c[0], c[1]]));
      if (d) { errors.push(`RAM conflict with “${o.name}”: both use ${ramRange(Math.max(c[0], d[0]), Math.min(c[0] + c[1], d[0] + d[1]) - Math.max(c[0], d[0]))}.`); continue; }
      const w = o.ramSeen?.find((x) => overlaps(x, [c[0], c[1]]));
      if (w && !c[2]) warnings.push(`“${o.name}” writes at ${hex(Math.max(w[0], c[0]))} to RAM the patch uses (${ramRange(c[0], c[1])}).`);
    }
    for (const d of o.ram ?? []) {
      if (d[2] || ram.some((c) => overlaps([c[0], c[1]], [d[0], d[1]]))) continue;
      const w = seen.find((x) => overlaps(x, [d[0], d[1]]));
      if (w) warnings.push(`The patch writes at ${hex(Math.max(w[0], d[0]))} to RAM of “${o.name}” (${ramRange(d[0], d[1])}).`);
    }
  }
  return { errors, warnings };
}

const key = (b: RatsBlock) => `${b.start}:${b.size}`;

// Temporary RATS tags over the reserved banks keep Asar's free space search out of them.
export function reserveTop(data: Uint8Array): Uint8Array | null {
  if (data.length <= RESERVED_TOP) return null;
  const saved = data.slice(RESERVED_TOP, data.length);
  for (let o = RESERVED_TOP; o + 0x8000 <= data.length; o += 0x8000) {
    const s = 0x8000 - 8 - 1;
    data.set([0x53, 0x54, 0x41, 0x52, s & 0xff, s >> 8, ~s & 0xff, (~s >> 8) & 0xff], o);
  }
  return saved;
}

export interface RegisterMeta {
  name: string;
  version?: string;
  hash: string;
  settings: Record<string, string>;
  kind?: PatchEntry['kind'];
  ram?: RamClaim[];
  archive?: Uint8Array;
}

// Records the change from `before` to `out` as one patch: new RATS blocks are its own free space, the
// written ranges outside them its segments (checked against the other patches, the editor's hooks,
// protected data and the reserved banks). On success rom.data becomes `out` and the entry is added.
export function registerChanges(rom: Rom, before: Uint8Array, beforeRats: RatsBlock[], out: Uint8Array, written: [number, number][], meta: RegisterMeta, warn: string[] = []): { errors: string[]; warnings: string[]; entry?: PatchEntry } {
  const after = new Rom(out);
  const known = new Set(beforeRats.map(key));
  const own = after.scanRats().filter((b) => !known.has(key(b)) && b.start < RESERVED_TOP);
  const ownRanges: [number, number][] = own.map((b) => [b.start, b.size + 8]);

  const segs: [number, number][] = [];
  for (const w of written) {
    for (const s of subtract(w, [...ownRanges, ...IGNORE])) segs.push(s);
  }
  // merge overlapping writes of several runs
  segs.sort((a, b) => a[0] - b[0]);
  for (let i = 1; i < segs.length; i++) {
    const p = segs[i - 1], c = segs[i];
    if (c[0] <= p[0] + p[1]) { p[1] = Math.max(p[1], c[0] + c[1] - p[0]); segs.splice(i--, 1); }
  }

  const errors: string[] = [];
  const warnings = [...warn];
  const others = listPatches(rom);
  for (const s of segs) {
    const where = `${pcHex(s[0])} (${s[1]} bytes)`;
    if (s[0] + s[1] > RESERVED_TOP) { errors.push(`The patch writes at ${where} to banks $7E/$7F, which are reserved for the editor.`); continue; }
    const p = others.find((o) => o.segs.some((t) => overlaps(t, s)) || o.own.some((t) => overlaps([t, (rom.isRatsAt(t) + 8)], s)));
    if (p) { errors.push(`Conflict with patch “${p.name}” at ${where}.`); continue; }
    const hit = beforeRats.find((b) => overlaps([b.start, b.size + 8], s));
    if (hit) { errors.push(`The patch overwrites protected data (RATS block at ${pcHex(hit.start)}) at ${where}.`); continue; }
    for (const bi of BUILTINS) {
      const h = bi.hooks.find(([a, n]) => overlaps([snesToPc(a), n], s));
      if (!h) continue;
      if (bi.installed(rom)) errors.push(`Conflict with ${bi.name}: the patch changes its hook at ${hex(h[0])}.`);
      else warnings.push(`The patch uses ${hex(h[0])}; ${bi.name} can no longer be installed afterwards.`);
    }
  }
  const ram = (meta.ram ?? []).map(([a, n, sh]): RamClaim => { const w = wramAddr(a) < 0 ? a : wramAddr(a); return sh ? [w, n, sh] : [w, n]; });
  const ramSeen = longWrites(out, [...own.map((b): [number, number] => [b.start + 8, b.size]), ...segs]);
  const rc = ramConflicts(ram, ramSeen, others);
  errors.push(...rc.errors);
  warnings.push(...rc.warnings);
  if (errors.length) return { errors, warnings };

  const original = segs.map(([pc, n]) => {
    const o = new Uint8Array(n);
    if (pc < before.length) o.set(before.subarray(pc, Math.min(pc + n, before.length)));
    return o;
  });
  rom.data = out;
  const entry = addPatch(rom, {
    id: `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 7)}`,
    name: meta.name,
    version: meta.version,
    hash: meta.hash,
    defines: meta.settings,
    applied: new Date().toISOString(),
    segs,
    own: own.map((b) => b.start),
    check: patchedHash(after, segs),
    kind: meta.kind,
    ...(ram.length ? { ram } : {}),
    ...(ramSeen.length ? { ramSeen } : {}),
  }, original, meta.archive);
  return { errors: [], warnings, entry };
}

export function applyPatch(rom: Rom, src: PatchSource): ApplyResult {
  const defines = { sa1: '0', smwe: '1', ...(src.defines ?? {}) };
  const before = rom.data;
  const beforeRats = rom.scanRats();
  const files = new Map(src.files);
  if (!files.has('smwe.asm')) files.set('smwe.asm', editorInclude(rom));
  // all runs on input; the last result, or the failed one
  const runAll = (input: Uint8Array): { r: AsarResult; steps: AsarResult[] } => {
    const steps: AsarResult[] = [];
    const fs = new Map(files);
    let main = src.main;
    for (;;) {
      const r = assemble(input, fs, main, defines);
      steps.push(r);
      if (!r.ok) return { r, steps };
      const nx = src.next?.(steps);
      if (!nx) return { r, steps };
      for (const [k, v] of nx.files ?? []) fs.set(k, v);
      main = nx.main;
      input = r.rom;
    }
  };
  let input = before.slice();
  let saved = reserveTop(input);
  let { r, steps } = runAll(input);
  // Asar expanded the ROM to 4 MB and used the reserved banks: run again with them blocked
  if (r.ok && !saved && r.rom.length > RESERVED_TOP && steps.some((x) => x.blocks.some((b) => b.pc + b.size > RESERVED_TOP))) {
    input = new Uint8Array(0x400000);
    input.set(before);
    input[0x7fd7] = 0x0c;
    saved = reserveTop(input);
    ({ r, steps } = runAll(input));
  }
  const prints = steps.flatMap((x) => x.prints);
  const fail = (errors: string[], warnings: string[] = []): ApplyResult => ({
    ok: false, errors, warnings, prints, steps, asar: { errors: r.errors, warnings: r.warnings },
  });
  if (!r.ok) return fail(r.errors.map((e) => e.full), steps.flatMap((x) => x.warnings.map((w) => w.full)));
  const out = r.rom;
  if (saved) out.set(saved, RESERVED_TOP);

  const reg = registerChanges(rom, before, beforeRats, out, steps.flatMap((x) => x.blocks.map((b): [number, number] => [b.pc, b.size])), {
    name: src.name, version: src.version, hash: sourceHash(src), settings: src.settings ?? src.defines ?? {}, kind: src.kind, ram: src.ram, archive: src.archive,
  }, steps.flatMap((x) => x.warnings.map((w) => w.full)));
  if (!reg.entry) return fail(reg.errors, reg.warnings);
  const { entry, warnings } = reg;
  return { ok: true, errors: [], warnings, prints, entry, labels: Object.assign({}, ...steps.map((x) => x.labels)), steps, asar: { errors: [], warnings: r.warnings } };
}

// Restores the original bytes and frees the patch's free space. Returns warnings; throws if a patch
// applied later depends on this one.
export function uninstallPatch(rom: Rom, id: string): string[] {
  const all = listPatches(rom);
  const i = all.findIndex((p) => p.id === id);
  if (i < 0) throw new Error('Patch is not installed');
  const p = all[i];
  const mine: [number, number][] = [...p.segs, ...p.own.map((o): [number, number] => [o, rom.isRatsAt(o) + 8])];
  for (const later of all.slice(i + 1)) {
    if (later.segs.some((s) => mine.some((m) => overlaps(m, s)))) {
      throw new Error(`“${later.name}” changes code of this patch – remove “${later.name}” first.`);
    }
  }
  const warnings: string[] = [];
  if (patchedHash(rom, p.segs) !== p.check) warnings.push('Bytes changed by the patch have been modified since; they are reset to their original state anyway.');
  const orig = backupBytes(rom, p);
  let o = 0;
  for (const [pc, n] of p.segs) { rom.writeAt(pc, orig.subarray(o, o + n)); o += n; }
  for (const t of p.own) {
    const n = rom.isRatsAt(t);
    if (n > 0) rom.fillAt(t, n + 8);
  }
  removeEntry(rom, id);
  return warnings;
}

// uninstall + apply with new sources/defines (on failure the patch is uninstalled: run it in an edit
// session, romedit.ts, which puts the ROM back)
export function reapplyPatch(rom: Rom, id: string, src: PatchSource): ApplyResult {
  const warnings = uninstallPatch(rom, id);
  const r = applyPatch(rom, src);
  r.warnings.unshift(...warnings);
  return r;
}
