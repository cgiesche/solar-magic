// FastROM's jump targets (ADR 0007): plays the clean game as the tests do – boot and the title screen
// with its demo, a new game on the overworld, every level with the input of the VRAM test – and records
// every long jump it executes from the ROM into banks $00–$3F: the bank byte of each JSL/JML operand,
// and for each JML [abs] the bank byte of the ROM table entry its pointer was read from. The FastROM
// patch (fastrom.ts) sets bit 7 of these bytes.
//   node tools/fastromsites.ts           checks src/core/fastromsites.ts against a fresh run
//   node tools/fastromsites.ts --write   writes it
import { readFileSync, writeFileSync } from 'node:fs';
import { Rom } from '../src/core/rom.ts';
import { LevelEmulator } from '../src/core/levelemu.ts';
import { GM, RAM } from '../src/core/ram.ts';
import { cleanImage } from './fixture.ts';

const OUT = 'src/core/fastromsites.ts';
const frames = Number(process.argv.find((a) => a.startsWith('--frames='))?.slice(9) ?? 360);
const rom = new Rom(cleanImage());
const emu = new LevelEmulator(rom);
const s = emu.snes, cpu = s.cpu, d = rom.data;

const jumps = new Set<number>(); // ROM offsets of JSL/JML operands' bank bytes
const tables = new Set<number>(); // ROM offsets of the bank bytes of 24-bit pointers JML [abs] went through
const loose = new Map<string, number>(); // JML [abs] whose pointer was not read from the ROM as a whole: where → count

// a ROM address (code or data), not WRAM, I/O or the editor's overlay ($FE/$FF)
const inRom = (a: number) => (a & 0xffff) >= 0x8000 && ((a >> 16) & 0x7e) !== 0x7e;
// the ROM offsets of the latest data reads (no fetches)
const RING = 64;
const ring = new Int32Array(RING).fill(-1);
let at = 0;
const read = s.read.bind(s);
s.read = (a: number) => {
  if (!cpu.inFetch && inRom(a)) ring[at++ & (RING - 1)] = s.romOffset(a);
  return read(a);
};
const exec = cpu.exec.bind(cpu);
cpu.exec = (op: number) => {
  const from = cpu.opPc;
  if ((op === 0x22 || op === 0x5c) && inRom(from)) {
    const o = (cpu.pbr << 16) | cpu.pc; // the operand
    const bank = s.peek((o & 0xff0000) | ((o + 2) & 0xffff)), lo = s.peek(o) | (s.peek((o & 0xff0000) | ((o + 1) & 0xffff)) << 8);
    if (bank < 0x40 && lo >= 0x8000) jumps.add(s.romOffset((o & 0xff0000) | ((o + 2) & 0xffff)));
  }
  exec(op);
  if (op === 0xdc && cpu.pbr < 0x40 && cpu.pc >= 0x8000 && inRom(from)) {
    // the bank byte of a 24-bit pointer in the ROM equal to the target, among the latest data reads; or a
    // 16-bit pointer in the target's bank (the game's ExecutePtr takes the bank from its caller, which
    // runs in the fast banks already)
    let found = -1, local = false;
    for (let i = 1; i <= RING && found < 0; i++) {
      const r = ring[(at - i) & (RING - 1)];
      if (r >= 2 && d[r] === cpu.pbr && d[r - 1] === cpu.pc >> 8 && d[r - 2] === (cpu.pc & 0xff)) found = r;
      else if (r >= 0 && d[r] === (cpu.pc & 0xff) && d[r + 1] === cpu.pc >> 8 && r >> 15 === cpu.pbr) local = true;
    }
    if (found >= 0) tables.add(found);
    else if (!local) { const k = from.toString(16).padStart(6, '0'); loose.set(k, (loose.get(k) ?? 0) + 1); }
  }
};

const t0 = Date.now();
const w = s.wram;
const input = (f: number) => 0x4100 | (f % 70 < 34 ? 0x8000 : 0) | (f % 200 > 150 ? 0x0200 : 0) | (f % 300 > 240 ? 0x0800 : 0);
const play = (n: number, joy: (f: number) => number) => { for (let f = 0; f < n; f++) { s.joy1 = joy(f); s.runFrame(); } s.joy1 = 0; };

// boot, then the title screen until its demo has run
emu.boot();
play(1500, () => 0);
// a new game: the overworld, walking about
emu.startGame(0);
play(600, (f) => [0x0100, 0x0800, 0x0200, 0x0400][(f >> 6) & 3] | (f % 64 === 40 ? 0x8000 : 0));
// every level, entered as the tests do, and played
for (let n = 0; n < 0x200; n++) {
  if (!emu.load(n).ok) continue;
  for (let g = 0; w[RAM.gameMode] !== GM.level && g < 200; g++) s.runFrame();
  play(frames, input);
}

const sorted = (x: Set<number>) => [...x].sort((a, b) => a - b);
const hex = (v: number) => '0x' + v.toString(16).padStart(5, '0');
const list = (x: number[]) => x.map(hex).join(', ').replace(/((?:0x[0-9a-f]+, ){11}0x[0-9a-f]+), /g, '$1,\n  ');
const text = `// Generated by tools/fastromsites.ts from a run of the clean game – do not edit (ADR 0007).
// ROM offsets of bank bytes the FastROM patch (fastrom.ts) sets bit 7 of.

// operands of JSL/JML into banks $00–$3F
export const JUMP_SITES: readonly number[] = [
  ${list(sorted(jumps))},
];

// 24-bit pointers in ROM tables that JML [abs] goes through
export const TABLE_SITES: readonly number[] = [
  ${list(sorted(tables))},
];
`;
console.log(`${jumps.size} jump sites, ${tables.size} table sites in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
for (const [k, n] of loose) console.log(`JML [abs] at $${k} without a ROM pointer (${n}×)`);
if (process.argv.includes('--write')) writeFileSync(OUT, text);
else {
  let old = '';
  try { old = readFileSync(OUT, 'utf8'); } catch { /* none yet */ }
  console.log(old === text ? 'ok   site list matches a fresh run' : `FAIL site list differs from a fresh run (node tools/fastromsites.ts --write)`);
  if (old !== text) process.exitCode = 1;
}
