#!/bin/sh
# Takes the ASM of BOWSIE (Better Overworld Sprite Insertion Engine, Arinsu; https://github.com/arinsuwu/bowsie,
# BSD-2-Clause) from its release into src/vendor/bowsie/bowsie.ts: the sprite system for a vanilla overworld
# (vldc9.asm with its defines, macro.asm, MaxTile's defines and code) and the shared routines, as strings. The tool
# itself (C++) is not taken: the editor does its steps (src/core/bowsie.ts). Two changes (FIXES below) for BOWSIE
# without MaxTile, which the editor runs (BOWSIE's default is with it): MaxTile's requirement of Lunar Magic's "disable
# event path fade effect" is checked only when MaxTile is on (BOWSIE includes MaxTile's defines either way), and the
# priority OAM start is loaded as a word (`LDA #!oam_start_p` is `LDA #$00` with Asar: the define is a number 0, the
# next byte then taken as an opcode – the overworld crashed). Needs curl, unzip, node.
set -e
BOWSIE_TAG=v1.21
ROOT=$(cd "$(dirname "$0")/.." && pwd)
WORK=${BOWSIE_WORK:-$ROOT/node_modules/.cache/bowsie-$BOWSIE_TAG}
OUT=$ROOT/src/vendor/bowsie
if [ ! -d "$WORK/asm" ]; then
  mkdir -p "$WORK"
  curl -sL -o "$WORK/bowsie.zip" "https://github.com/arinsuwu/bowsie/releases/download/$BOWSIE_TAG/BOWSIE.$BOWSIE_TAG-static.zip"
  unzip -q -o "$WORK/bowsie.zip" -d "$WORK"
fi
mkdir -p "$OUT"
curl -sL -o "$OUT/LICENSE" "https://raw.githubusercontent.com/arinsuwu/bowsie/$BOWSIE_TAG/LICENSE"
node -e '
const fs = require("fs"), path = require("path");
const [work, out, tag] = process.argv.slice(1);
const FIXES = {
  "asm/vldc9.asm": [["        LDA #!oam_start_p\n", "        LDA.w #!oam_start_p ; (Solar Magic: a word)\n"]],
  "asm/maxtile_defines.asm": [["    if read1($04E6FA) != $96\n", "    if !bowsie_maxtile && read1($04E6FA) != $96 ; (Solar Magic: only with MaxTile)\n"]] };
const read = (f) => {
  let t = fs.readFileSync(path.join(work, f), "latin1").replace(/\r\n/g, "\n");
  for (const [a, b] of FIXES[f] ?? []) { if (!t.includes(a)) throw new Error(`${f}: "${a.trim()}" not found`); t = t.replace(a, b); }
  return t;
};
const sys = ["vldc9.asm", "vldc9_defines.asm", "macro.asm", "maxtile.asm", "maxtile_defines.asm"];
const routines = fs.readdirSync(path.join(work, "routines")).filter((f) => f.endsWith(".asm")).sort();
const obj = (names, dir) => "{\n" + names.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(read(dir + f))},`).join("\n") + "\n}";
fs.writeFileSync(path.join(out, "bowsie.ts"), [
  `// generated by tools/build-bowsie.sh from BOWSIE ${tag} (Arinsu; BSD-2-Clause, see LICENSE): its ASM (two changes, tools/build-bowsie.sh)`,
  `export const BOWSIE_VERSION = ${JSON.stringify(tag.slice(1))};`,
  `export const BOWSIE_ASM: Record<string, string> = ${obj(sys, "asm/")};`,
  `export const BOWSIE_ROUTINES: Record<string, string> = ${obj(routines, "routines/")};`,
  ""].join("\n"));
' "$WORK" "$OUT" "$BOWSIE_TAG"
echo "wrote $OUT/bowsie.ts"
