#!/bin/sh
# Builds AddmusicK (https://github.com/KungFuFurby/AddMusicKFF, by Kipernal; maintained since 1.0.6
# by Medic, HertzDevil, Vitor Vilela, Lui, KevinM, KungFuFurby and others) as WebAssembly into
# src/vendor/amk/, with Asar linked in as a library (the same sources as tools/build-asar.sh) and
# AddmusicK's own files (asm/, samples/, sound effects, original songs, lists) embedded.
# Needs Emscripten and git.
set -e
AMK_TAG=1.0.11
ASAR_TAG=v1.91
ROOT=$(cd "$(dirname "$0")/.." && pwd)
WORK=${AMK_WORK:-$ROOT/node_modules/.cache/amk-src}
ASAR=${ASAR_WORK:-$ROOT/node_modules/.cache/asar-src}
OUT=$ROOT/src/vendor/amk
command -v em++ >/dev/null 2>&1 || PATH=/usr/lib/emscripten:$PATH

if [ ! -d "$WORK/.git" ]; then
  mkdir -p "$(dirname "$WORK")"
  git clone -q https://github.com/KungFuFurby/AddMusicKFF "$WORK"
fi
git -C "$WORK" checkout -q $AMK_TAG
if [ ! -d "$ASAR/.git" ]; then
  git clone -q --depth 1 --branch $ASAR_TAG https://github.com/RPGHacker/asar "$ASAR"
fi
git -C "$ASAR" apply --check "$ROOT/tools/asar-wasm/normalize-paths.patch" 2>/dev/null && git -C "$ASAR" apply "$ROOT/tools/asar-wasm/normalize-paths.patch"

# AddmusicK's working directory as it expects it, embedded at /amk
DATA=$ROOT/node_modules/.cache/amk-data
rm -rf "$DATA"; mkdir -p "$DATA/music" "$DATA/SPCs" "$DATA/stats"
cp -r "$WORK/asm" "$WORK/samples" "$WORK/1DF9" "$WORK/1DFC" "$DATA/"
cp -r "$WORK/music/originals" "$DATA/music/"
cp "$WORK/Addmusic_list.txt" "$WORK/Addmusic_sample groups.txt" "$WORK/Addmusic_sound effects.txt" "$DATA/"
rm -rf "$DATA/asm/SNES/bin"; mkdir -p "$DATA/asm/SNES/bin"; touch "$DATA/asm/SNES/bin/.keep" "$DATA/SPCs/.keep" "$DATA/stats/.keep" # build outputs of the upstream repo

A=$ASAR/src/asar
M=$WORK/src/AddmusicK
# every function Asar's library exports gets the prefix asarlib_ (AddmusicK's names are pointers)
RENAME=$(grep -oE '^EXPORT [^(]*\basar_[a-z_]+\(' "$A/interface-lib.cpp" | grep -oE 'asar_[a-z_]+' | sort -u | sed 's/.*/-D&=lib&/; s/=libasar_/=asarlib_/' | tr '\n' ' ')
OBJ=$ROOT/node_modules/.cache/amk-obj
rm -rf "$OBJ"; mkdir -p "$OBJ"
for f in addr2line arch-65816 arch-spc700 arch-superfx assembleblock crc32 libcon libsmw libstr macro main \
         asar_math virtualfile warnings errors platform/file-helpers platform/linux/file-helpers-linux interface-lib; do
  em++ -O2 -std=c++14 -fexceptions -Dlinux -Dstricmp=strcasecmp -DASAR_SHARED $RENAME -I"$A" -Wno-varargs -Wno-unused-result \
    -c "$A/$f.cpp" -o "$OBJ/asar-$(basename $f).o"
done
for f in "$M/AddmusicK.cpp" "$M/globals.cpp" "$M/Music.cpp" "$M/SoundEffect.cpp" "$M/lodepng.cpp" \
         "$WORK/src/AM405Remover/AddMusic.cpp" "$ROOT/tools/amk-wasm/asarshim.cpp"; do
  em++ -O2 -std=c++17 -fexceptions -I"$M" -Wno-everything -c "$f" -o "$OBJ/amk-$(basename "$f" .cpp).o"
done
mkdir -p "$OUT"
# 200 MB initial memory: AddmusicK keeps 256 songs with 640 KB of loop tables each as globals
em++ -O2 -fexceptions "$OBJ"/*.o \
  --embed-file "$DATA@/amk" \
  -sMODULARIZE -sEXPORT_ES6 -sEXPORT_NAME=createAmk -sENVIRONMENT=web,worker,node \
  -sALLOW_MEMORY_GROWTH -sINITIAL_MEMORY=209715200 -sSTACK_SIZE=8388608 -sFILESYSTEM=1 \
  -sINVOKE_RUN=0 -sEXIT_RUNTIME=0 \
  -sEXPORTED_RUNTIME_METHODS=FS,callMain \
  -o "$OUT/amk.mjs"
# the original songs of AddmusicK's list (number, file, global?) for the editor's song list
awk 'BEGIN { print "// generated by tools/build-amk.sh from AddmusicK'"'"'s Addmusic_list.txt"; print "export const AMK_ORIGINALS: [number, string, boolean][] = [" }
  /^Globals:/ { g = "true" } /^Locals:/ { g = "false" }
  /^[0-9A-Fa-f][0-9A-Fa-f] / { n = $1; sub(/^[0-9A-Fa-f][0-9A-Fa-f][ \t]+/, ""); sub(/\r$/, ""); printf "  [0x%s, \"%s\", %s],\n", n, $0, g }
  END { print "];" }' "$WORK/Addmusic_list.txt" > "$OUT/originals.ts"
# the numbers of its own sound effects per bank (pointers to another one included): taken for custom ones
awk 'BEGIN { print "// the numbers of AddmusicK'"'"'s own sound effects per bank (Addmusic_sound effects.txt)"; print "export const AMK_SFX: Record<\"1DF9\" | \"1DFC\", number[]> = {" }
  { sub(/\r$/, "") } /^SFX1DF9:/ { if (b) print "],"; b = "1DF9"; printf "  \"1DF9\": ["; next } /^SFX1DFC:/ { if (b) print "],"; b = "1DFC"; printf "  \"1DFC\": ["; next }
  /^[0-9A-Fa-f][0-9A-Fa-f]?[ \t]/ && b { printf "0x%s, ", toupper($1) }
  END { print "],"; print "};" }' "$WORK/Addmusic_sound effects.txt" >> "$OUT/originals.ts"
echo "AddmusicK $AMK_TAG -> $OUT"
